"""Build a small, reproducible eye patch from the pinned original character."""
import argparse
from base64 import b64encode
from hashlib import sha256
import json
from itertools import groupby
from struct import pack
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
PACK = ROOT / "apps/agent/src/buildurprofile_agent/resources/pixel-avatar-v1"
TARGET = ROOT / "apps/web/src/assets/pixel-gaze-v1/index.ts"
BOUNDS = (441, 528, 837, 608)
EYES = ((457, 538, 578, 598), (700, 538, 821, 598))


def encode(image):
    encoded = bytearray()
    for pixel, group in groupby(image.get_flattened_data()):
        count = sum(1 for _ in group)
        while count:
            run = min(count, 65535)
            encoded.extend(pack(">H4B", run, *pixel))
            count -= run
    return b64encode(encoded).decode("ascii")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify checked-in resources without writing")
    args = parser.parse_args()
    # The existing loader is the authority for pinned resource validation.
    from buildurprofile_agent.skills.pixel_avatar_layers import load_pixel_avatar_layers
    layers = load_pixel_avatar_layers()
    base = layers._image("base")
    glasses = layers._image("glasses")
    patch = base.crop(BOUNDS)
    plate = patch.copy()
    sprites = []
    for x1, y1, x2, y2 in EYES:
        sprites.append(encode(base.crop((x1, y1, x2, y2))))
        for x in range(x1, x2):
            for y in range(y1, y2):
                plate.putpixel((x-BOUNDS[0], y-BOUNDS[1]), base.getpixel((x, 600)))
    profiles = []
    for name, front in (("plain", Image.new("RGBA", patch.size)), ("frames", glasses.crop(BOUNDS))):
        original = Image.alpha_composite(patch, front)
        profiles.append(dict(id=name, original=encode(original), plate=encode(plate), foreground=encode(front)))
    data = dict(bounds=dict(x=441, y=528, width=396, height=80),
                eyes=[dict(x=x1-441,y=y1-528,width=x2-x1,height=y2-y1,sprite=sprite)
                      for (x1,y1,x2,y2),sprite in zip(EYES,sprites)], profiles=profiles,
                sourceManifestSha256=sha256((PACK/'manifest.json').read_bytes()).hexdigest())
    TARGET.parent.mkdir(parents=True,exist_ok=True)
    module = '// Generated by scripts/prepare-pixel-gaze-assets.py.\nexport const pixelGazeAssets = '+json.dumps(data,separators=(',',':'))+' as const;\n'
    if args.check:
        if TARGET.read_text() != module:
            raise SystemExit("Pixel gaze resources differ from pinned inputs")
    else:
        TARGET.write_text(module)


if __name__ == "__main__":
    main()
